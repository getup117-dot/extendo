const C = require('../beyspot/core.js');
const assert = require('node:assert/strict');

module.exports = async function check() {
  const checks=[];
  assert.equal(C.validPoint({lat:0,lng:0}),true);
  for(const lat of [null,'',Infinity,91])assert.equal(C.validPoint({lat,lng:0}),false);
  checks.push('座標の境界・空欄を検証');
  const a=C.coarse(35.68951,139.6917), b=C.coarse(35.68952,139.6917);
  assert.deepEqual(a,b);assert.notEqual(a.lat,35.68951);
  checks.push('概略位置の格子が元の緯度を漏らさない');
  const point={lat:35,lng:139,updated_at:new Date(1000000).toISOString(),expires_at:new Date(2000000).toISOString()};
  assert.equal(C.validShare(point,1000000),true);
  assert.equal(C.validShare(point,1300000),false);
  assert.equal(C.validShare(point,2100000),false);
  checks.push('位置は更新停止5分・期限切れで非表示');
  assert.deepEqual(C.coordsFromMapUrl('https://www.google.com/maps/@35.5,139.5,14z'),{lat:35.5,lng:139.5});
  assert.deepEqual(C.coordsFromMapUrl('https://maps.apple.com/?ll=35.5,139.5'),{lat:35.5,lng:139.5});
  assert.deepEqual(C.coordsFromMapUrl('https://www.openstreetmap.org/#map=15/35.5/139.5'),{lat:35.5,lng:139.5});
  assert.equal(C.coordsFromMapUrl('https://google.com.evil.example/maps/@35.5,139.5,14z'),null);
  assert.equal(C.coordsFromMapUrl('91,139'),null);
  checks.push('地図URL・直接座標・不正URLを検証');
  const draft={title:'対戦',place:'会場',details:'',date:'2099-01-01',endDate:'2099-01-02',start:'23:00',end:'01:00',lat:35,lng:139};
  assert.ok(Date.parse(C.eventRecord(draft,'test',0).ends_at)>Date.parse(C.eventRecord(draft,'test',0).starts_at));
  assert.throws(()=>C.eventRecord({...draft,endDate:'2099-01-01',end:'22:00'},'test',0));
  assert.equal(C.localDateTime('2099-02-31','12:00'),null);
  assert.throws(()=>C.eventRecord(draft,null,0));
  checks.push('日付をまたぐ予定・不正日時・未認証を検証');
  assert.equal(C.validateConnection('https://test.supabase.co','sb_publishable_test'),true);
  assert.throws(()=>C.validateConnection('https://test.supabase.co','sb_secret_test'));
  checks.push('秘密キーを接続設定から排除');
  const queue=C.createShareQueue(),events=[];let release,start;
  const started=new Promise(r=>{start=r});const gate=new Promise(r=>{release=r});
  const token=queue.begin();
  const write=queue.enqueue(token,async()=>{events.push('write-start');start();await gate;events.push('write-end');});
  await started;
  const late=queue.enqueue(token,()=>events.push('late-write'));
  const stop=queue.stop(()=>events.push('delete'));
  release();await Promise.all([write,late,stop]);
  assert.deepEqual(events,['write-start','write-end','delete']);
  assert.equal(queue.current(token),false);
  const next=queue.begin();await queue.enqueue(next,()=>events.push('new-write'));
  assert.equal(events.at(-1),'new-write');
  checks.push('停止前の送信完了後に削除・遅れたGPS送信を破棄');
  return checks;
};
